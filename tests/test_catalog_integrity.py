    def test_live_provenance_dimensions_uniqueness_and_zero_specimens(self):
        """(c) All 575 targets: live provenance, 1440x[900..2400] & 390x[844..2400], zero specimens, zero dupes."""
        all_slugs = sorted([p.name for p in TARGETS_DIR.iterdir() if p.is_dir()])
        self.assertEqual(len(all_slugs), 575, f"Expected 575 targets, found {len(all_slugs)}")

        seen_hashes: dict[str, str] = {}
        duplicates: list[tuple[str, str]] = []
        specimens: list[str] = []
        non_live: list[str] = []
        bad_dims: list[str] = []
        blocked_issues: list[tuple[str, list[str]]] = []

        for slug in all_slugs:
            if is_blocked_target(slug):
                br = evaluate_blocked_target(slug)
                if not br["ok"]:
                    blocked_issues.append((slug, br["issues"]))
                continue

            bp_file = TARGETS_DIR / slug / "prompt-blueprint.md"
            bp_txt = bp_file.read_text(encoding="utf-8", errors="ignore")
            fm, _ = split_frontmatter(bp_txt)
            cap_m = re.search(r"^capture:\s*(\S+)", fm, re.MULTILINE)
            cap_d = re.search(r"^capture_desktop:\s*(\S+)", fm, re.MULTILINE)
            cap_m_v = re.search(r"^capture_mobile:\s*(\S+)", fm, re.MULTILINE)
            if "specimen" in bp_txt[:500] or "Design Specimen" in bp_txt:
                specimens.append(slug)
            if not (cap_m and cap_m.group(1) == "live" and cap_d and cap_d.group(1) == "live" and cap_m_v and cap_m_v.group(1) == "live"):
                non_live.append(slug)

            d_png = TARGETS_DIR / slug / "assets" / "desktop.png"
            m_png = TARGETS_DIR / slug / "assets" / "mobile.png"
            if not d_png.exists() or not m_png.exists():
                bad_dims.append(f"{slug}: missing desktop/mobile PNG")
                continue
            dw, dh = read_png_dims(d_png)
            mw, mh = read_png_dims(m_png)
            if dw != 1440 or not (900 <= dh <= 2400):
                bad_dims.append(f"{slug} desktop={dw}x{dh}")
            if mw != 390 or not (844 <= mh <= 2400):
                bad_dims.append(f"{slug} mobile={mw}x{mh}")

            for label, p in ((f"{slug}/desktop.png", d_png), (f"{slug}/mobile.png", m_png)):
                h = hashlib.sha256(p.read_bytes()).hexdigest()
                if h in seen_hashes:
                    duplicates.append((seen_hashes[h], label))
                else:
                    seen_hashes[h] = label

        self.assertEqual(specimens, [], f"Found {len(specimens)} synthetic specimen targets: {specimens[:10]}")
        self.assertEqual(non_live, [], f"Found {len(non_live)} non-live analyzed targets: {non_live[:10]}")
        self.assertEqual(bad_dims, [], f"Found {len(bad_dims)} out-of-bounds PNGs: {bad_dims[:10]}")
        self.assertEqual(duplicates, [], f"Found duplicate PNG SHA256 hashes: {duplicates[:10]}")
        self.assertEqual(blocked_issues, [], f"Found C15 issues on blocked targets: {blocked_issues[:10]}")

