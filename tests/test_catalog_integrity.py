    def test_visual_metrics_blank_vs_textured(self):
        """Blank solid PNG is flagged unhealthy; high-contrast checkerboard PNG passes."""
        blank_buf = io.BytesIO()
        Image.new("RGB", (200, 200), (16, 16, 16)).save(blank_buf, format="PNG")
        m_blank = compute_png_visual_metrics(blank_buf.getvalue(), top_fold_height=200)
        self.assertTrue(m_blank["valid"])
        self.assertLess(m_blank["gray_std"], 1.0)
        self.assertTrue(is_visual_unhealthy_for_tier2(m_blank))

        rich_img = Image.new("RGB", (200, 200), (245, 245, 245))
        px = rich_img.load()
        for y in range(200):
            for x in range(200):
                if (x // 10 + y // 10) % 2 == 0:
                    px[x, y] = (20, 40, 80)
        rich_buf = io.BytesIO()
        rich_img.save(rich_buf, format="PNG")
        m_rich = compute_png_visual_metrics(rich_buf.getvalue(), top_fold_height=200)
        self.assertTrue(m_rich["valid"])
        self.assertGreater(m_rich["gray_std"], 50.0)
