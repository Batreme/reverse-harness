def read_png_dims(p: Path) -> tuple[int, int]:
    with open(p, "rb") as f:
        d = f.read(24)
        if len(d) >= 24 and d[:8] == b"\x89PNG\r\n\x1a\n" and d[12:16] == b"IHDR":
            return struct.unpack(">II", d[16:24])
    return (0, 0)


